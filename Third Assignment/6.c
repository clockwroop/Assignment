#include <stdio.h> // 표준 입출력 헤더 파일을 추가한다.

int main(void) // 메인 함수를 정의한다.
{
    int N; // N 변수를 정수 타입으로 정의한다.
    
    printf("N을 입력하세요: "); // N 입력 프롬프트를 출력한다.
    scanf("%d", &N); // N 값을 정수 타입으로 입력받는다.

    if (N < 1 || N > 9) // N이 1~9 범위를 벗어나는지 검사한다.
    {
        printf("오류: N이 범위를 벗어났습니다.\n"); // 범위 초과 오류 메시지를 출력한다.
        return 0; // 프로그램을 종료한다.
    }

    for (int i = 1; i <= N; i++) // 1행부터 N행까지 반복한다.
    {
        for (int k = 1; k <= i; k++) // 각 행에서 1부터 i까지 곱셈을 반복한다.
        {
            if (k == i) // 행의 마지막 숫자인지 검사한다.
                printf("%d", i * k); // 공백 없이 숫자를 출력한다.
            else // 행의 중간 숫자인 경우 실행한다.
                printf("%d ", i * k); // 숫자 뒤에 공백을 포함하여 출력한다.
        }
        printf("\n"); // 한 행의 출력이 끝나면 줄바꿈을 수행한다.
    }

    return 0; // 함수를 종료한다.
}