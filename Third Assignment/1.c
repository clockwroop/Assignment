#include <stdio.h> // 표준 입출력 헤더 파일을 추가한다.

int main(void) // 메인 함수를 정의한다.
{
    int balance, amount; // 잔액과 출금액 변수를 정수 타입으로 정의한다.
    
    printf("현재 잔액을 입력하세요: "); // 잔액 입력 프롬프트를 출력한다.
    scanf("%d", &balance); // 잔액을 정수 타입으로 입력받는다.
    
    printf("출금액을 입력하세요: "); // 출금액 입력 프롬프트를 출력한다.
    scanf("%d", &amount); // 출금액을 정수 타입으로 입력받는다.
    
    if (amount <= 0) // 출금액이 0 이하인지 검사한다.
    {
        printf("출금액이 음수입니다.\n"); // 잘못된 출금액 오류 메시지를 출력한다.
    }
    else if (amount % 1000 != 0) // 출금액이 1,000원 단위가 아닌지 검사한다.
    {
        printf("출금액이 1,000원 단위가 아닙니다.\n"); // 단위 불일치 오류 메시지를 출력한다.
    }
    else if (amount > balance) // 출금액이 현재 잔액을 초과하는지 검사한다.
    {
        printf("출금액이 잔액을 초과했습니다.\n"); // 잔액 부족 오류 메시지를 출력한다.
    }
    else // 모든 정상 출금 조건을 만족할 때 실행한다.
    {
        balance -= amount; // 잔액에서 출금액을 차감한다.
        printf("출금 후 잔액: %d원\n", balance); // 출금 후 잔액을 출력한다.
    }
    
    return 0; // 함수를 종료한다.
}