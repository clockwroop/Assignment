#include <stdio.h> // 표준 입출력 헤더 파일을 추가한다.

int main(void) // 메인 함수를 정의한다.
{
    int n, isPrime = 1; // 입력값과 소수 판별 플래그 변수를 정의하고 초기화한다.
    
    printf("2 이상의 정수를 입력하세요: "); // 정수 입력 프롬프트를 출력한다.
    scanf("%d", &n); // 정수 n을 입력받는다.
    
    if (n < 2) // 2 미만의 값이 입력되었는지 검사한다.
    {
        printf("입력값이 잘못되었습니다.\n"); // 오류 메시지를 출력한다.
        return 0; // 프로그램을 종료한다.
    }

    for (int i = 2; i <= n - 1; i++) // 2부터 n-1까지 1씩 증가시키며 반복한다.
    {
        if (n % i == 0) // 나누어떨어지는 약수가 존재하는지 검사한다.
        {
            isPrime = 0; // 소수 플래그를 거짓(0)으로 변경한다.
            break; // 반복 검사를 즉시 종료한다.
        }
    }

    if (isPrime == 1) // 소수 플래그가 참인지 검사한다.
        printf("%d은 소수입니다.\n", n); // 소수 결과문을 출력한다.
    else // 소수 플래그가 거짓인 경우 실행한다.
        printf("%d은 소수가 아닙니다.\n", n); // 합성수 결과문을 출력한다.

    return 0; // 함수를 종료한다.
}