#include <stdio.h> // 표준 입출력 헤더 파일을 추가한다.

int main(void) // 메인 함수를 정의한다.
{
    char c; // 변수 c 를 문자 타입으로 정의한다.
    
    printf("문자를 입력하세요: "); // 문자를 입력 받는 프롬프트를 출력한다.
    c = getchar(); // 한개의 문자를 입력받아 변수 c 에 저장한다.
    c ++; // 변수 c 의 ASCII 값에 1을 더한다.
    
    printf("다음 문자: "); // 다음 문자을 출력함을 설명한다.
    putchar(c); // 한개의 문자를 출력한다.
    printf("\n");

    return 0; // 함수를 종료한다.
}