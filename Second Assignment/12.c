#include <stdio.h> // 표준 입출력 헤더 파일을 추가한다.

int main(void) // 메인 함수를 정의한다.
{
    int a = 5, b = 5; // a와 b를 정수 타입으로 정의 후 5로 초기화한다.
    int x, y; // 연산 결과를 저장할 변수 x와 y를 정수 타입으로 정의한다.
    
    x = 2 * (a++); // 후치 증가를 사용해 곱셈을 수행한 후 a를 1 증가시킨다.
    y = 2 * (++b); // 전치 증가를 사용해 b를 1 증가시킨 후 곱셈을 수행한다.
    
    printf("후치 연산 결과: a=%d, x=%d\n", a, x); // 후치 적용 결과를 정수 타입으로 출력한다.
    printf("전치 연산 결과: b=%d, y=%d\n", b, y); // 전치 적용 결과를 정수 타입으로 출력한다.
    
    return 0; // 함수를 종료한다.
}